let cachedPath: string | null = null;

// Gabungkan semua titik daratan jadi SATU path SVG (titik bulat lewat stroke-linecap round).
export const getLandPath = (): string => {
  if (cachedPath) return cachedPath;
  const parts: string[] = [];
  WORLD_ROWS.forEach((hex, r) => {
    const y = (r + 0.5) * MAP_STEP;
    for (let i = 0; i < hex.length; i++) {
      const nib = parseInt(hex[i], 16);
      for (let b = 0; b < 4; b++) {
        if (nib & (8 >> b)) {
          const c = i * 4 + b;
          parts.push(`M${(c + 0.5) * MAP_STEP} ${y}h0.01`);
        }
      }
    }
  });
  cachedPath = parts.join('');
  return cachedPath;
};

// Koordinat (lintang, bujur) -> posisi di peta
export const project = (lat: number, lon: number) => ({ x: lon + 180, y: MAP_TOP_LAT - lat });
